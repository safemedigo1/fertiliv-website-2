export const APPOINTMENT_COMMUNICATION_PUBLISHED_LOCALES = Object.keys(appointmentCommunicationLocaleResources);
export const APPOINTMENT_COMMUNICATION_FALLBACK_ONLY_LOCALES = ["other"] as const;

export type AppointmentCommunicationLocaleResolution = {
  requestedLocale?: string | null;
  deliveredLocale: string;
  fallbackUsed: boolean;
};

/**
 * Converted Patients retain Patient identity for delivery, while their linked Lead
 * remains the authoritative language profile used by Patient editing. The helper
 * is recipient-scoped: a Partner never inherits the primary recipient language.
 */
export function resolveRecipientProfileLanguage(
  directProfileLanguage?: string | null,
  convertedLeadProfileLanguage?: string | null,
): string | null {
  return convertedLeadProfileLanguage?.trim().toLowerCase()
    || directProfileLanguage?.trim().toLowerCase()
    || null;
}

export function hasPublishedAppointmentCommunicationLocale(value?: string | null): value is string {
  return Boolean(value && Object.prototype.hasOwnProperty.call(appointmentCommunicationLocaleResources, value));
}

export function resolveAppointmentCommunicationLocale(requestedLocale?: string | null): AppointmentCommunicationLocaleResolution {
  const normalized = requestedLocale?.trim().toLowerCase() || undefined;
  if (hasPublishedAppointmentCommunicationLocale(normalized)) {
    return { requestedLocale: normalized, deliveredLocale: normalized, fallbackUsed: false };
  }
  return {
    requestedLocale: normalized,
    deliveredLocale: APPOINTMENT_COMMUNICATION_FALLBACK_LOCALE,
    fallbackUsed: Boolean(normalized && normalized !== APPOINTMENT_COMMUNICATION_FALLBACK_LOCALE),
  };
}

export function getAppointmentCommunicationLocaleResource(locale?: string | null): AppointmentCommunicationLocaleResource {
  const resolution = resolveAppointmentCommunicationLocale(locale);
  return appointmentCommunicationLocaleResources[resolution.deliveredLocale as keyof typeof appointmentCommunicationLocaleResources]!;
}
